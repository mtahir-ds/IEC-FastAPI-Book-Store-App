"""Pydantic Schemas for Data Validation and Serialization.

This module defines the request and response schemas (data transfer objects)
for the Book entity using Pydantic to ensure input validation and ORM serialization.
"""

from pydantic import BaseModel  # Base class for defining data validation models and serialization schemas


class BookBase(BaseModel):
    """Base Pydantic model defining shared fields for a book.

    Used as the parent model to avoid repeating common fields across create and read schemas.
    """

    title: str  # Title of the book; validated as a required string
    description: str  # Detailed description or summary of the book; validated as a required string
    author: str  # Name of the author; validated as a required string
    year: int  # Publication year; validated as a required integer


class BookCreate(BookBase):
    """Schema representing the request payload for creating a new book.

    Inherits all core attributes from BookBase without requiring an ID.
    """

    pass  # No extra fields needed; creation uses the base fields as-is


class Book(BookBase):
    """Schema representing a book returned in API responses.

    Extends BookBase to include the database-generated ID and configure ORM data parsing.
    """

    id: int  # Unique identifier generated by the database for the book record

    class config:
        orm_mode = True  # Pydantic v1 setting to allow reading data from ORM model instances
        from_attribute = True  # Pydantic v2 configuration intended to parse data from ORM object attributes
